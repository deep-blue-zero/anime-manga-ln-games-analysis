#!/usr/bin/env python3
"""Generate the Character Index v2 discovery surface deterministically.

The surface is a compact root index plus one page per registry namespace, so
no generated file grows with the whole registry's detail.
"""

from __future__ import annotations

import argparse
from pathlib import Path, PurePosixPath
from typing import Any, Mapping, Sequence
from urllib.parse import quote

from character_index_core import (
    CHARACTER_INDEX_PAGE_PREFIX,
    CHARACTER_INDEX_PATH,
    DISCOVERY_INPUT_PATHS,
    AuthorityGraph,
    DomainError,
    GitSnapshot,
    alias_sort_key,
    atomic_write_text,
    character_index_page_path,
    current_layout_errors,
    decode_json,
    discovery_partition_path,
    managed_worktree_directory,
    read_discovery_registry,
    record_namespace,
    render_schema_diagnostics,
    schema_diagnostics,
    sort_key,
    validate_discovery_records,
    validate_schema_document,
)


DIMENSION_ORDER = (
    "BEHAVIOR",
    "PSYCHOLOGY",
    "SPEECH",
    "ETHICS",
    "RELATIONSHIPS",
    "IDEOLOGY",
    "DECISION_MAKING",
)

HEADER = """# Character Analysis Index

> Generated under `CHARACTER_INDEX_V2_C14N_1`; do not edit this file by hand.

The `main` branch of this public, owner-maintained Git repository is the analytical authority. Native Google Sheets remain controlled Drive authoring surfaces whose revisions become effective only after verified export and Git merge; reference-only artifacts and the primary-source/extraction workspace remain outside Git authority.

This discovery surface answers: “Where is substantial, reviewed analysis of this precisely scoped character subject?” It is not a migration ledger and does not claim reconstruction readiness. Mention counts, cast lists, transcripts, source text, and incidental references do not qualify by themselves.

Each reviewed analysis subject is listed once below and links to its generated namespace page under `characters/index/`, which gives entity aliases, subject scope, analytical coverage, and reviewed current evidence. The curated records are the namespace partitions `characters/registry/<namespace>.jsonl`, specified in `characters/README.md`.

"""

PAGE_HEADER = """# Character Analysis Index: `{namespace}`

> Generated under `CHARACTER_INDEX_V2_C14N_1`; do not edit this file by hand.

Reviewed analysis subjects in the `{namespace}` namespace of the [Character Analysis Index](../../CHARACTER_ANALYSIS_INDEX.md). Their curated records are [`{partition}`](../registry/{namespace}.jsonl). Inclusion does not claim reconstruction readiness.

## Reviewed entries

"""
PAGE_LINK_PREFIX = "../../"


def _alias_text(alias: Mapping[str, Any]) -> str:
    qualifiers = [alias["language"], alias["kind"]]
    if alias.get("ambiguous"):
        qualifiers.append("ambiguous")
    rendered = f"{alias['value']} ({', '.join(qualifiers)})"
    if alias.get("note") is not None:
        rendered += f" — {alias['note']}"
    return rendered


def _coverage_label(coverage: Mapping[str, Any]) -> str:
    prefix = f"{coverage['medium']} {coverage['unit']}"
    if coverage["scope_type"] == "RANGE":
        return f"{prefix} {coverage['start']}–{coverage['through']} (inclusive)"
    if coverage["scope_type"] == "DISCRETE":
        return f"{prefix} " + ", ".join(coverage["locators"])
    return f"{prefix}: {coverage['scope_note']}"


def _markdown_target(path: str, anchor: str | None) -> str:
    encoded_path = "/".join(quote(segment, safe="-._~") for segment in path.split("/"))
    if anchor is None:
        return encoded_path
    return encoded_path + "#" + quote(anchor, safe="-._~:")


def _markdown_link_label(value: str) -> str:
    return value.replace("\\", "\\\\").replace("[", "\\[").replace("]", "\\]")


def _table_cell(value: str) -> str:
    return value.replace("\\", "\\\\").replace("|", "\\|")


def _table_link_label(value: str) -> str:
    return _markdown_link_label(value).replace("|", "\\|")


def _leaf_subjects(
    record: Mapping[str, Any], by_subject: Mapping[str, Mapping[str, Any]]
) -> list[Mapping[str, Any]]:
    leaves: dict[str, Mapping[str, Any]] = {}

    def expand(subject_id: str) -> None:
        child = by_subject[subject_id]
        if child["subject_kind"] == "COMPOSITE_MODEL":
            for component in child["component_subject_ids"]:
                expand(component)
        else:
            leaves[subject_id] = child

    for component in record.get("component_subject_ids", []):
        expand(component)
    return [leaves[key] for key in sorted(leaves)]


def _record_order(record: Mapping[str, Any]) -> tuple[Any, ...]:
    return (
        sort_key(record["preferred_name"]),
        sort_key(record["subject_label"]),
        record["analysis_subject_id"].encode("ascii"),
    )


def _entity_groups(
    included: Sequence[Mapping[str, Any]],
) -> list[list[Mapping[str, Any]]]:
    grouped: dict[str, list[Mapping[str, Any]]] = {}
    for record in included:
        grouped.setdefault(record["character_entity_id"], []).append(record)
    for entity_id in grouped:
        grouped[entity_id] = sorted(grouped[entity_id], key=_record_order)
    entity_ids = sorted(
        grouped,
        key=lambda entity_id: (
            *_record_order(grouped[entity_id][0]),
            entity_id.encode("ascii"),
        ),
    )
    return [grouped[entity_id] for entity_id in entity_ids]


def _entity_anchor(record: Mapping[str, Any]) -> str:
    return record["character_entity_id"].split(":", 1)[1]


def _alias_values(record: Mapping[str, Any]) -> list[str]:
    values: list[str] = []
    for field in ("entity_aliases", "subject_aliases"):
        for alias in sorted(record[field], key=alias_sort_key):
            if alias["value"] not in values:
                values.append(alias["value"])
    return values


def render_outputs(
    records: Sequence[Mapping[str, Any]], authority: AuthorityGraph
) -> dict[str, str]:
    """Return every generated discovery output, keyed by repository path."""

    included = [
        record for record in records if record.get("curation_status") == "INCLUDED"
    ]
    if not included:
        return {
            CHARACTER_INDEX_PATH: HEADER
            + "_No reviewed entries are present in the character registry._\n"
        }
    by_subject = {record["analysis_subject_id"]: record for record in records}
    by_namespace: dict[str, list[Mapping[str, Any]]] = {}
    for record in included:
        namespace = record_namespace(record)
        if namespace is None:
            raise DomainError(f"{record.get('analysis_subject_id')}: invalid character_entity_id")
        by_namespace.setdefault(namespace, []).append(record)
    namespaces = sorted(by_namespace, key=lambda item: item.encode("ascii"))
    outputs = {
        character_index_page_path(namespace): _render_page(
            namespace, by_namespace[namespace], by_subject, authority
        )
        for namespace in namespaces
    }
    lines = [
        HEADER.rstrip(),
        "",
        "## Namespaces",
        "",
        "| Namespace | Reviewed subjects |",
        "| --- | ---: |",
    ]
    for namespace in namespaces:
        lines.append(
            f"| [`{namespace}`]({character_index_page_path(namespace)}) "
            f"| {len(by_namespace[namespace])} |"
        )
    lines.extend(
        [
            "",
            "## Reviewed subjects",
            "",
            "| Character | Subject | Analysis subject ID | Aliases |",
            "| --- | --- | --- | --- |",
        ]
    )
    for record in sorted(included, key=_record_order):
        page = character_index_page_path(record_namespace(record))  # type: ignore[arg-type]
        aliases = "; ".join(_table_cell(value) for value in _alias_values(record)) or "—"
        lines.append(
            f"| [{_table_link_label(record['preferred_name'])}]"
            f"({page}#{_entity_anchor(record)}) "
            f"| {_table_cell(record['subject_label'])} "
            f"| `{record['analysis_subject_id']}` "
            f"| {aliases} |"
        )
    outputs[CHARACTER_INDEX_PATH] = "\n".join(lines) + "\n"
    return outputs


def _render_page(
    namespace: str,
    included: Sequence[Mapping[str, Any]],
    by_subject: Mapping[str, Mapping[str, Any]],
    authority: AuthorityGraph,
) -> str:
    header = PAGE_HEADER.format(
        namespace=namespace, partition=discovery_partition_path(namespace)
    )
    lines = [header.rstrip(), ""]
    for subjects in _entity_groups(included):
        entity = subjects[0]
        lines.extend(
            [
                f'<a id="{_entity_anchor(entity)}"></a>',
                "",
                f"### {entity['preferred_name']}",
                "",
                f"- Entity ID: `{entity['character_entity_id']}`",
                "- Entity aliases:",
            ]
        )
        entity_aliases = sorted(entity["entity_aliases"], key=alias_sort_key)
        if entity_aliases:
            for alias in entity_aliases:
                lines.append(f"  - {_alias_text(alias)}")
        else:
            lines.append("  - _None._")
        lines.append("")
        for record in subjects:
            lines.extend(
                [
                    f"#### Subject: {record['subject_label']}",
                    "",
                    f"- Analysis subject ID: `{record['analysis_subject_id']}`",
                    f"- Series: `{record['series_id']}`",
                ]
            )
            if record["subject_kind"] == "COMPOSITE_MODEL":
                leaves = _leaf_subjects(record, by_subject)
                continuities = sorted({leaf["continuity_id"] for leaf in leaves})
                lines.append("- Continuity: **Composite analytical model (not a continuity)**")
                lines.append(
                    "- Effective continuity scope (derived): "
                    + ", ".join(f"`{item}`" for item in continuities)
                )
                lines.append(
                    "- Components: "
                    + ", ".join(
                        f"`{item}`" for item in sorted(record["component_subject_ids"])
                    )
                )
            else:
                lines.append(f"- Continuity: `{record['continuity_id']}`")
            if record.get("incarnation_id") is not None:
                lines.append(f"- Incarnation: `{record['incarnation_id']}`")
            if record.get("state_id") is not None:
                lines.append(f"- State: `{record['state_id']}`")
            lines.append(f"- Inclusion basis: `{record['inclusion_basis']}`")
            dimensions = [
                item for item in DIMENSION_ORDER if item in record["analytical_dimensions"]
            ]
            if set(record["analytical_dimensions"]) != set(dimensions):
                raise DomainError(
                    f"{record['analysis_subject_id']}: generator received an unknown analytical dimension"
                )
            lines.append(
                "- Analytical dimensions: "
                + ", ".join(f"`{item}`" for item in dimensions)
            )
            subject_aliases = sorted(record["subject_aliases"], key=alias_sort_key)
            lines.append("- Subject aliases:")
            if subject_aliases:
                for alias in subject_aliases:
                    lines.append(f"  - {_alias_text(alias)}")
            else:
                lines.append("  - _None._")
            lines.append("- Analytical coverage:")
            for coverage in sorted(
                record["analytical_coverage"], key=lambda item: item["coverage_id"]
            ):
                component = (
                    f"; component `{coverage['component_subject_id']}`"
                    if "component_subject_id" in coverage
                    else ""
                )
                lines.append(
                    f"  - `{coverage['coverage_id']}`: {_coverage_label(coverage)}"
                    f"; continuity `{coverage['continuity_id']}`{component}"
                )
            lines.append("- Reviewed current evidence:")
            for evidence in sorted(record["evidence"], key=lambda item: item["evidence_id"]):
                classification = authority.classification(evidence["repository_path"])
                if evidence["review_state"] != "REVIEWED" or not authority.current_eligible(
                    evidence["repository_path"]
                ):
                    raise DomainError(
                        f"included evidence is not reviewed/current: "
                        f"{record['analysis_subject_id']}#{evidence['evidence_id']} "
                        f"({classification})"
                    )
                target = PAGE_LINK_PREFIX + _markdown_target(
                    evidence["repository_path"], evidence.get("anchor")
                )
                marker = (
                    " — **active provisional authority**"
                    if classification == "ACTIVE_PROVISIONAL_CURRENT"
                    else ""
                )
                lines.append(
                    f"  - [`{evidence['evidence_id']}` — "
                    f"{_markdown_link_label(evidence['label'])}]({target})"
                    f"{marker}"
                )
            lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def _snapshot(root: Path, mode: str, commit: str | None) -> GitSnapshot:
    if mode == "commit":
        if commit is None:
            raise DomainError("--commit is required with --snapshot commit")
        return GitSnapshot.from_commit(root, commit)
    if commit is not None:
        raise DomainError("--commit is valid only with --snapshot commit")
    if mode == "index":
        return GitSnapshot.from_index(root)
    return GitSnapshot.from_worktree(root)


def generated_output_errors(snapshot: GitSnapshot, expected: Mapping[str, str]) -> list[str]:
    """Compare a snapshot's generated discovery outputs with the rendered set."""

    errors: list[str] = []
    for path in sorted(expected, key=lambda item: item.encode("utf-8")):
        entry = snapshot.get(path)
        if entry is None:
            errors.append(f"generated character index output is missing: {path}")
        elif entry.mode != "100644" or entry.data != expected[path].encode("utf-8"):
            errors.append(f"{path} is out of date")
    for path in sorted(snapshot.entries, key=lambda item: item.encode("utf-8")):
        if path.startswith(CHARACTER_INDEX_PAGE_PREFIX) and path not in expected:
            errors.append(f"{path} is not a generated namespace page; regenerate the character index")
    return errors


def write_outputs(root: Path, snapshot: GitSnapshot, rendered: Mapping[str, str]) -> list[str]:
    """Write changed outputs and remove stale namespace pages; return the paths to stage."""

    page_directory = managed_worktree_directory(root, CHARACTER_INDEX_PAGE_PREFIX)
    changed: list[str] = []
    for path in sorted(rendered, key=lambda item: item.encode("utf-8")):
        target = root.joinpath(*PurePosixPath(path).parts)
        data = rendered[path].encode("utf-8")
        if target.is_file() and not target.is_symlink() and target.read_bytes() == data:
            continue
        target.parent.mkdir(parents=True, exist_ok=True)
        atomic_write_text(target, rendered[path])
        changed.append(path)
    stale = {path for path in snapshot.entries if path.startswith(CHARACTER_INDEX_PAGE_PREFIX)}
    if page_directory.is_dir():
        stale.update(CHARACTER_INDEX_PAGE_PREFIX + item.name for item in page_directory.iterdir())
    for path in sorted(stale - set(rendered), key=lambda item: item.encode("utf-8")):
        target = root.joinpath(*PurePosixPath(path).parts)
        if target.is_file() or target.is_symlink():
            target.unlink()
        changed.append(path)
    return changed


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--repo", type=Path)
    parser.add_argument("--snapshot", choices=["worktree", "index", "commit"], default="worktree")
    parser.add_argument("--commit")
    args = parser.parse_args()
    root = args.repo.resolve() if args.repo else Path(__file__).resolve().parents[1]
    snapshot = _snapshot(root, args.snapshot, args.commit)
    required_entries = {name: snapshot.get(path) for name, path in DISCOVERY_INPUT_PATHS.items()}
    missing = [
        path
        for name, path in DISCOVERY_INPUT_PATHS.items()
        if required_entries[name] is None or required_entries[name].mode != "100644"
    ]
    if missing:
        raise DomainError(f"snapshot lacks required regular paths: {missing}")
    registry = read_discovery_registry(snapshot)
    layout_errors = current_layout_errors(registry)
    if layout_errors:
        raise DomainError("\n".join(layout_errors))
    records = registry.records
    if args.snapshot == "worktree" and records:
        raise DomainError(
            "worktree bytes cannot establish materialization; use an exact Git index or commit snapshot"
        )
    schema = decode_json(
        required_entries["schema"].data,  # type: ignore[union-attr]
        f"{snapshot.identity}:character-analysis-index.schema.json",
    )
    if not isinstance(schema, dict):
        raise DomainError("character discovery schema is not a JSON object")
    validate_schema_document(schema, "character discovery schema")
    diagnostics = []
    for row in registry.rows:
        diagnostics.extend(
            schema_diagnostics(row.record, schema, row.path, line_number=row.line_number)
        )
    failures = render_schema_diagnostics(diagnostics)
    if failures:
        raise DomainError("\n".join(failures))
    authority = AuthorityGraph(snapshot)
    series_registry = decode_json(
        required_entries["series"].data,  # type: ignore[union-attr]
        f"{snapshot.identity}:series/registry.json",
    )
    if not isinstance(series_registry, dict):
        raise DomainError("series registry is not a JSON object")
    failures = authority.errors + validate_discovery_records(
        records, series_registry, snapshot=snapshot, authority=authority, labels=registry.labels
    )
    if failures:
        raise DomainError("\n".join(sorted(set(failures))))
    rendered = render_outputs(records, authority)
    if args.check:
        errors = generated_output_errors(snapshot, rendered)
        if errors:
            raise SystemExit("\n".join(errors))
        return 0
    if args.snapshot == "commit":
        raise DomainError("commit-snapshot generation is check-only")
    for path in write_outputs(root, snapshot, rendered):
        print(f"generated output to stage: {path}")
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except DomainError as exc:
        raise SystemExit(f"FAIL: {exc}") from exc
