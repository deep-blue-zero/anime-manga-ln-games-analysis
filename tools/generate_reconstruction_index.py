#!/usr/bin/env python3
"""Generate the character reconstruction capability index deterministically.

The index projects only recorded assessment state from the capability registry
and the immutable basis commits it names. It never reads live currentness, so
ordinary analytical or discovery publication cannot make it out of date.

The surface is a compact root index plus one page per registry namespace, so
no generated file grows with the whole registry's detail.
"""

from __future__ import annotations

import argparse
from pathlib import Path, PurePosixPath
from typing import Any, Mapping, Sequence
from urllib.parse import quote

from character_index_core import (
    CURRENT_CLAIM_STATUSES,
    RECONSTRUCTION_DIMENSIONS,
    RECONSTRUCTION_INDEX_PAGE_PREFIX,
    RECONSTRUCTION_INDEX_PATH,
    RECONSTRUCTION_REGISTRY_PREFIX,
    RECONSTRUCTION_SCHEMA_PATH,
    SCENARIO_CATEGORIES,
    DomainError,
    GitSnapshot,
    atomic_write_text,
    current_reconstruction_layout_errors,
    decode_json,
    evaluate_reconstruction_assessments,
    managed_worktree_directory,
    read_reconstruction_registry,
    reconstruction_index_page_path,
    reconstruction_partition_path,
    render_schema_diagnostics,
    schema_diagnostics,
    validate_schema_document,
)


REPOSITORY_URL = "https://github.com/deep-blue-zero/anime-manga-ln-games-analysis"
DIMENSION_ORDER = (
    "PSYCHOLOGICAL_MODEL",
    "LONGITUDINAL_STATE",
    "VOICE_REGISTER",
    "MUNDANE_BEHAVIOR",
    "RELATIONSHIP_CONDITIONING",
    "INTERIORITY",
    "CONFLICT_BEHAVIOR",
    "ETHICAL_DELIBERATION",
    "HUMOR_PLAY",
    "SOURCE_COMPLETENESS",
    "NEGATIVE_EVIDENCE",
    "TEMPORAL_SPECIFICITY",
)
SCENARIO_ORDER = (
    "DIALOGUE",
    "CROSS_SCENARIO",
    "MUNDANE_SOCIAL",
    "ETHICAL_DELIBERATION",
    "ROMANCE_RELATIONSHIP",
    "PROFESSIONAL_CONTEXT",
)
STATUS_ORDER = ("REVIEWED", "CANDIDATE", "STALE", "SUPERSEDED", "UNASSESSED")
STATUS_TEXT = {
    "REVIEWED": (
        "human-reviewed at its basis commit; this is historical publication state, "
        "not certification that it applies to later commits"
    ),
    "CANDIDATE": "**provisional; not human-reviewed**",
    "STALE": "historical record; not current readiness",
    "SUPERSEDED": "historical record; replaced by a successor assessment",
    "UNASSESSED": "no capability claims",
}
TIER_TEXT = {
    "A": "reconstruction-grade for disciplined novel-scenario work",
    "B": "strong inferential model with explicit bounded uncertainty",
    "C": "specialist-supported interpretation without unconstrained simulation support",
    "D": "substantial distributed evidence without a strong operational model",
    "E": "limited/local evidence suitable for bounded canon questions only",
}

HEADER = """# Character Reconstruction Capability Index

> Generated from the capability registry partitions `characters/reconstruction_capabilities/<namespace>/<subject>.jsonl` by `tools/generate_reconstruction_index.py` under `CHARACTER_INDEX_V2_C14N_1`; do not edit this file by hand.

This index answers: “What did the reconstruction evaluator record about the extrapolations an exact, commit-bound evidence set can responsibly support?” It is a deterministic publication snapshot of recorded assessment states. It is not an independent authority and it does not certify present-day readiness.

Inclusion in the [Character Analysis Index](../CHARACTER_ANALYSIS_INDEX.md), character prominence, source-appearance frequency, and the existence of a monograph are never capability grades. The governing contract is the [Character Reconstruction Capability Specification](RECONSTRUCTION_CAPABILITY_SPEC.md); evaluator operations follow [Character reconstruction maintenance](../governance/policies/CHARACTER_RECONSTRUCTION_MAINTENANCE.md). Substantive character analysis remains in its canonical `series/` or `studies/` home.

Each recorded assessment is listed once below and links to its generated namespace page under `characters/reconstruction_index/`, which gives the full recorded claims, limits and evidence at the basis commit.

## Recorded state versus current applicability

- A recorded `REVIEWED` status means human review at the assessment's basis commit. Later integrated evidence, discovery, or authority changes can make it effectively stale before the evaluator records `STALE`.
- `CANDIDATE` assessments are provisional and have not been human-reviewed.
- `STALE` and `SUPERSEDED` assessments are historical records, reproducible at their basis commits.
- Verify present applicability against an exact integrated commit before relying on any assessment with `python tools/reconstruction_status.py currentness --snapshot commit --commit <full-main-sha>`. Only the derived state `CURRENT_REVIEWED` means that a human-reviewed assessment still applies to that commit.

"""

PAGE_HEADER = """# Character Reconstruction Capability Index: `{namespace}`

> Generated from the capability registry partitions under `{partition_directory}` by `tools/generate_reconstruction_index.py` under `CHARACTER_INDEX_V2_C14N_1`; do not edit this file by hand.

Recorded assessments of subjects in the `{namespace}` namespace of the [Character Reconstruction Capability Index](../CHARACTER_RECONSTRUCTION_INDEX.md), which states how recorded status differs from current applicability. A recorded status is historical publication state, never certification of present-day readiness.

## Recorded assessments

"""


def _escape(value: str) -> str:
    result = []
    for char in value:
        if char in "\\`*_[]()<>|#":
            result.append("\\" + char)
        else:
            result.append(char)
    return "".join(result)


def _permalink(commit: str, path: str, anchor: str | None) -> str:
    encoded = "/".join(quote(segment, safe="-._~") for segment in path.split("/"))
    target = f"{REPOSITORY_URL}/blob/{commit}/{encoded}"
    if anchor is not None:
        target += "#" + quote(anchor, safe="-._~:")
    return target


def _scope_text(scope: Mapping[str, Any]) -> str:
    if scope.get("continuity_id") is None:
        components = ", ".join(
            f"`{item}`"
            for item in sorted(
                scope.get("component_subject_ids", []), key=lambda item: item.encode("ascii")
            )
        )
        return f"composite analytical model (not a continuity); components {components}"
    parts = [f"continuity `{scope['continuity_id']}`"]
    if scope.get("incarnation_id") is not None:
        parts.append(f"incarnation `{scope['incarnation_id']}`")
    if scope.get("state_id") is not None:
        parts.append(f"state `{scope['state_id']}`")
    return "; ".join(parts)


def _tier_text(record: Mapping[str, Any]) -> str:
    tier = record["overall_tier"]
    if tier == "NOT_ASSESSED":
        return "_Not assessed._"
    qualifier = "provisional " if record["assessment_status"] == "CANDIDATE" else ""
    if record["assessment_status"] not in CURRENT_CLAIM_STATUSES:
        qualifier = "historical "
    return f"{qualifier}`{tier}` — {TIER_TEXT[tier]}"


def _render_assessment(
    record: Mapping[str, Any], entries: Sequence[Mapping[str, Any]]
) -> list[str]:
    status = record["assessment_status"]
    scope = record["assessment_scope"]
    lines = [
        f'<a id="{record["assessment_id"]}"></a>',
        "",
        f"#### Assessment `{record['assessment_id']}`",
        "",
        f"- Recorded status: `{status}` — {STATUS_TEXT[status]}",
        f"- Entity: `{record['character_entity_id']}`",
        f"- Scope: {_scope_text(scope)}",
        f"- Source boundary: {_escape(scope['source_boundary'])}",
        "- Temporal boundary: "
        + (
            _escape(scope["temporal_boundary"])
            if scope.get("temporal_boundary") is not None
            else "_Not applicable._"
        ),
        f"- Basis commit: `{scope['basis_commit']}`",
        f"- Evidence set: `{scope['evidence_set_algorithm']}` `{scope['evidence_set_sha256']}`",
        f"- Method: {_escape(scope['assessment_method'])} (version `{scope['assessment_method_version']}`)",
        f"- Overall tier: {_tier_text(record)}",
    ]
    scenarios = {item["scenario"]: item for item in record["scenario_readiness"]}
    if set(scenarios) != set(SCENARIO_CATEGORIES):
        raise DomainError(f"{record['assessment_id']}: generator received incomplete scenarios")
    lines.append(
        "- Scenario readiness: "
        + "; ".join(f"`{name}` {scenarios[name]['state']}" for name in SCENARIO_ORDER)
    )
    for name in SCENARIO_ORDER:
        claim = scenarios[name]
        for condition in claim.get("conditions", []):
            lines.append(f"  - `{name}` condition: {_escape(condition)}")
        cross = claim.get("cross_scenario_scope")
        if cross is not None:
            lines.append(
                f"  - `{name}` bounds: chronology {_escape(cross['assumed_chronology'])}; "
                f"interlocutor {_escape(cross['interlocutor_relationship'])}; settings "
                + "; ".join(_escape(item) for item in cross["setting_constraints"])
            )
    dimensions = {item["dimension"]: item for item in record["dimensions"]}
    if set(dimensions) != set(RECONSTRUCTION_DIMENSIONS):
        raise DomainError(f"{record['assessment_id']}: generator received incomplete dimensions")
    lines.append(
        "- Dimension grades: "
        + "; ".join(f"`{name}` {dimensions[name]['grade']}" for name in DIMENSION_ORDER)
    )
    lines.append("- Known limits:")
    limits = sorted(record["known_limits"], key=lambda item: item["limit_id"].encode("ascii"))
    if limits:
        for limit in limits:
            kind = "evidence-backed limitation" if limit["support_kind"] == "EVIDENCE_BACKED" else "evidence gap"
            lines.append(f"  - `{limit['limit_id']}` ({kind}): {_escape(limit['statement'])}")
    else:
        lines.append("  - _None recorded._")
    lines.append("- Evidence at basis commit:")
    if entries:
        for entry in entries:
            reference = f"{entry['analysis_subject_id']}#{entry['evidence_id']}"
            target = _permalink(scope["basis_commit"], entry["repository_path"], entry["anchor"])
            lines.append(f"  - [`{reference}`]({target})")
    else:
        lines.append("  - _None._")
    if record.get("supersedes_assessment_id") is not None:
        lines.append(f"- Supersedes: `{record['supersedes_assessment_id']}`")
    if record.get("superseded_by_assessment_id") is not None:
        lines.append(f"- Superseded by: `{record['superseded_by_assessment_id']}`")
    if record.get("stale_reason") is not None:
        lines.append(f"- Stale reason: {_escape(record['stale_reason'])}")
    lines.append("")
    return lines


def _record_order(records: Sequence[Mapping[str, Any]], index: int) -> tuple[bytes, int, bytes]:
    record = records[index]
    return (
        record["analysis_subject_id"].encode("ascii"),
        STATUS_ORDER.index(record["assessment_status"]),
        record["assessment_id"].encode("ascii"),
    )


def _namespace(record: Mapping[str, Any]) -> str:
    return record["analysis_subject_id"].split(":", 1)[0]


def _relative_link(from_path: str, target: str) -> str:
    """A relative Markdown link from the page at ``from_path`` to ``target``."""

    source = PurePosixPath(from_path).parent.parts
    destination = PurePosixPath(target).parts
    common = 0
    while common < min(len(source), len(destination)) and source[common] == destination[common]:
        common += 1
    return "/".join(
        [".."] * (len(source) - common)
        + [quote(segment, safe="-._~@") for segment in destination[common:]]
    )


def _page_link(record: Mapping[str, Any]) -> str:
    """Link from the root index to an assessment's block on its namespace page."""

    page = reconstruction_index_page_path(_namespace(record))
    return _relative_link(RECONSTRUCTION_INDEX_PATH, page) + "#" + quote(record["assessment_id"], safe="-._~")


def _partition_link(subject_id: str) -> str:
    """Link from a namespace page to a subject's registry file."""

    page = reconstruction_index_page_path(subject_id.split(":", 1)[0])
    return _relative_link(page, reconstruction_partition_path(subject_id))


def _render_page(
    namespace: str,
    records: Sequence[Mapping[str, Any]],
    indexes: Sequence[int],
    basis_entries: Mapping[int, Sequence[Mapping[str, Any]]],
) -> str:
    header = PAGE_HEADER.format(
        namespace=namespace, partition_directory=f"{RECONSTRUCTION_REGISTRY_PREFIX}{namespace}/"
    )
    lines = [header.rstrip(), ""]
    current_subject = None
    for index in indexes:
        record = records[index]
        if record["analysis_subject_id"] != current_subject:
            current_subject = record["analysis_subject_id"]
            lines.extend(
                [
                    f"### Subject `{current_subject}`",
                    "",
                    f"- Registry file: [`{reconstruction_partition_path(current_subject)}`]"
                    f"({_partition_link(current_subject)})",
                    "",
                ]
            )
        if index not in basis_entries:
            raise DomainError(f"{record['assessment_id']}: basis evidence is unresolved")
        lines.extend(_render_assessment(record, basis_entries[index]))
    return "\n".join(lines).rstrip() + "\n"


def render_outputs(
    records: Sequence[Mapping[str, Any]],
    basis_entries: Mapping[int, Sequence[Mapping[str, Any]]],
) -> dict[str, str]:
    """Return every generated reconstruction output, keyed by repository path."""

    if not records:
        return {
            RECONSTRUCTION_INDEX_PATH: HEADER
            + "_No reconstruction capability assessments have been published. Infrastructure "
            "activation does not establish that any character is reconstruction-ready._\n"
        }
    counts = {status: 0 for status in STATUS_ORDER}
    for record in records:
        counts[record["assessment_status"]] += 1
    ordered = sorted(range(len(records)), key=lambda index: _record_order(records, index))
    by_namespace: dict[str, list[int]] = {}
    for index in ordered:
        by_namespace.setdefault(_namespace(records[index]), []).append(index)
    namespaces = sorted(by_namespace, key=lambda item: item.encode("ascii"))
    outputs = {
        reconstruction_index_page_path(namespace): _render_page(
            namespace, records, by_namespace[namespace], basis_entries
        )
        for namespace in namespaces
    }
    lines = [HEADER.rstrip(), ""]
    lines.append(
        "- Recorded totals: "
        + "; ".join(f"`{status}` {counts[status]}" for status in STATUS_ORDER if counts[status])
    )
    lines.extend(
        [
            "",
            "## Namespaces",
            "",
            "| Namespace | Subjects | Assessments |",
            "| --- | ---: | ---: |",
        ]
    )
    for namespace in namespaces:
        relative = _relative_link(RECONSTRUCTION_INDEX_PATH, reconstruction_index_page_path(namespace))
        subjects = {records[index]["analysis_subject_id"] for index in by_namespace[namespace]}
        lines.append(f"| [`{namespace}`]({relative}) | {len(subjects)} | {len(by_namespace[namespace])} |")
    lines.extend(
        [
            "",
            "## Recorded assessments",
            "",
            "| Subject | Assessment | Recorded status | Overall tier | Basis commit |",
            "| --- | --- | --- | --- | --- |",
        ]
    )
    for index in ordered:
        record = records[index]
        lines.append(
            f"| `{record['analysis_subject_id']}` "
            f"| [`{record['assessment_id']}`]({_page_link(record)}) "
            f"| `{record['assessment_status']}` "
            f"| `{record['overall_tier']}` "
            f"| `{record['assessment_scope']['basis_commit']}` |"
        )
    outputs[RECONSTRUCTION_INDEX_PATH] = "\n".join(lines) + "\n"
    return outputs


def generated_output_errors(snapshot: GitSnapshot, expected: Mapping[str, str]) -> list[str]:
    """Compare a snapshot's generated reconstruction outputs with the rendered set."""

    errors: list[str] = []
    for path in sorted(expected, key=lambda item: item.encode("utf-8")):
        entry = snapshot.get(path)
        if entry is None or not entry.qualifies_as_evidence:
            errors.append(f"generated reconstruction index output is missing: {path}")
        elif entry.data != expected[path].encode("utf-8"):
            errors.append(f"{path} is out of date")
    for path in sorted(snapshot.entries, key=lambda item: item.encode("utf-8")):
        if path.startswith(RECONSTRUCTION_INDEX_PAGE_PREFIX) and path not in expected:
            errors.append(
                f"{path} is not a generated namespace page; regenerate the reconstruction index"
            )
    return errors


def write_outputs(root: Path, snapshot: GitSnapshot, rendered: Mapping[str, str]) -> list[str]:
    """Write changed outputs and remove stale namespace pages; return the paths to stage."""

    page_directory = managed_worktree_directory(root, RECONSTRUCTION_INDEX_PAGE_PREFIX)
    changed: list[str] = []
    for path in sorted(rendered, key=lambda item: item.encode("utf-8")):
        target = root.joinpath(*PurePosixPath(path).parts)
        data = rendered[path].encode("utf-8")
        if target.is_file() and not target.is_symlink() and target.read_bytes() == data:
            continue
        target.parent.mkdir(parents=True, exist_ok=True)
        atomic_write_text(target, rendered[path])
        changed.append(path)
    stale = {path for path in snapshot.entries if path.startswith(RECONSTRUCTION_INDEX_PAGE_PREFIX)}
    if page_directory.is_dir():
        stale.update(RECONSTRUCTION_INDEX_PAGE_PREFIX + item.name for item in page_directory.iterdir())
    for path in sorted(stale - set(rendered), key=lambda item: item.encode("utf-8")):
        target = root.joinpath(*PurePosixPath(path).parts)
        if target.is_file() or target.is_symlink():
            target.unlink()
        changed.append(path)
    return changed


def load_and_render(snapshot: GitSnapshot, repository: Path) -> dict[str, str]:
    """Validate the registry's historical integrity, then render its projection.

    The snapshot must store the registry in the current partitioned layout; an
    absent registry is a missing input.
    """

    schema_entry = snapshot.get(RECONSTRUCTION_SCHEMA_PATH)
    if schema_entry is None or schema_entry.mode != "100644":
        raise DomainError(f"snapshot lacks required regular paths: {[RECONSTRUCTION_SCHEMA_PATH]}")
    registry = read_reconstruction_registry(snapshot)
    layout_errors = current_reconstruction_layout_errors(registry)
    if layout_errors:
        raise DomainError("\n".join(layout_errors))
    schema = decode_json(schema_entry.data, f"{snapshot.identity}:{RECONSTRUCTION_SCHEMA_PATH}")
    if not isinstance(schema, dict):
        raise DomainError("reconstruction capability schema is not a JSON object")
    validate_schema_document(schema, "reconstruction capability schema")
    diagnostics = []
    for row in registry.rows:
        diagnostics.extend(
            schema_diagnostics(row.record, schema, row.path, line_number=row.line_number)
        )
    failures = render_schema_diagnostics(diagnostics)
    if failures:
        raise DomainError("\n".join(failures))
    records = registry.records
    evaluation = evaluate_reconstruction_assessments(records, repository)
    if evaluation.errors:
        raise DomainError("\n".join(evaluation.errors))
    return render_outputs(records, evaluation.basis_entries)


def _snapshot(root: Path, mode: str, commit: str | None) -> GitSnapshot:
    if mode == "commit":
        if commit is None:
            raise DomainError("--commit is required with --snapshot commit")
        return GitSnapshot.from_commit(root, commit)
    if commit is not None:
        raise DomainError("--commit is valid only with --snapshot commit")
    if mode == "index":
        return GitSnapshot.from_index(root)
    return GitSnapshot.from_worktree(root)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--repo", type=Path)
    parser.add_argument("--snapshot", choices=["worktree", "index", "commit"], default="worktree")
    parser.add_argument("--commit")
    args = parser.parse_args()
    root = args.repo.resolve() if args.repo else Path(__file__).resolve().parents[1]
    snapshot = _snapshot(root, args.snapshot, args.commit)
    rendered = load_and_render(snapshot, root)
    if args.check:
        errors = generated_output_errors(snapshot, rendered)
        if errors:
            raise SystemExit("\n".join(errors))
        return 0
    if args.snapshot == "commit":
        raise DomainError("commit-snapshot generation is check-only")
    for path in write_outputs(root, snapshot, rendered):
        print(f"generated output to stage: {path}")
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except DomainError as exc:
        raise SystemExit(f"FAIL: {exc}") from exc
